/**
 * Config plugin: no OkHttp below 4.12.1 in the TV app (EBE-7061).
 *
 * Eight eMudhra intermediate certificates were found compromised in October 2026 (Mozilla and
 * Google, 22 Oct). Fire OS has no Google Play services, so Google's own block never reaches a
 * Fire TV, and the device's certificate store can still trust them. OkHttp 4.12.1 (and 5.5.1)
 * refuse them inside the app, whatever the device says. React Native's fetch, and so every
 * request to the care hub when it is served over https, goes through OkHttp.
 *
 * React Native asks for OkHttp 4.9.2 and another library raises it to 4.12.0, the version the
 * 1.1.0 APK of 29 Oct carried; 1.1.1 (versionCode 3) is the first build with this floor. OkHttp's
 * own BOM, added as a platform, gives every com.squareup.okhttp3 module (okhttp,
 * okhttp-urlconnection, logging-interceptor and the rest) a required version of 4.12.1. A required
 * version is a floor, not a pin: a library that asks for a later OkHttp still gets it, except an
 * OkHttp 5 before 5.5.1 (okhttp, okhttp-android or okhttp-jvm), which the build rejects.
 *
 * android/ is generated by `expo prebuild`, so the lines are added here rather than by hand. A
 * prebuild without --clean keeps the old build.gradle, so the block between the two markers is
 * replaced each time rather than added once.
 */
const { withAppBuildGradle } = require("expo/config-plugins");

const OKHTTP_FLOOR = "4.12.1";
// The 5.x line was fixed in 5.5.1: a library that pulls an earlier 5.x (or its alphas) fails the build.
// OkHttp 5 also publishes okhttp-android and okhttp-jvm, which a library can ask for directly and
// which the 4.12.1 BOM does not name, so each gets the same reject.
const OKHTTP_5_REJECT = "[5,5.5.1)";
const OKHTTP_5_MODULES = ["okhttp", "okhttp-android", "okhttp-jvm"];
const MARKER = "// withOkHttpFloor (EBE-7061)";
const END = "// end withOkHttpFloor";
const REJECTS = OKHTTP_5_MODULES.map(
  (m) => `        implementation("com.squareup.okhttp3:${m}") {
            version { reject("${OKHTTP_5_REJECT}") }
            because("OkHttp 5 before 5.5.1 still trusts the compromised eMudhra certificates (EBE-7061)")
        }`
).join("\n");
const BLOCK = `
${MARKER}: no OkHttp below ${OKHTTP_FLOOR}; see plugins/withOkHttpFloor.js.
dependencies {
    implementation(platform("com.squareup.okhttp3:okhttp-bom:${OKHTTP_FLOOR}"))
    constraints {
${REJECTS}
    }
}
${END}
`;

module.exports = function withOkHttpFloor(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== "groovy") {
      throw new Error(
        "withOkHttpFloor: android/app/build.gradle is not Groovy; the Expo template changed, update the plugin"
      );
    }
    let src = cfg.modResults.contents;
    const start = src.indexOf(MARKER);
    if (start !== -1) {
      // An earlier block: up to the end marker, or to the end of the file for the first version,
      // which had none and was always the last thing in the file.
      const end = src.indexOf(END, start);
      const cut = src.lastIndexOf("\n", start);
      src = src.slice(0, cut === -1 ? start : cut) + (end === -1 ? "" : src.slice(end + END.length + 1));
    }
    cfg.modResults.contents = src.replace(/\s*$/, "\n") + BLOCK;
    return cfg;
  });
};
